"""
CSV dataset loading, validation, and reproducible splitting.

Contract
--------
- The CSV must have at least one numeric feature column followed by exactly
  one label column (the last column).
- Feature columns must be numeric.
- The label column must be non-null and is coerced to string.
- At least two distinct labels must be present.
- The train/test split is stratified, deterministic (random_state=42) and is
  created exactly once per Dataset instance. It must NOT be regenerated by
  later operations.
"""
from __future__ import annotations

import os
from dataclasses import dataclass
from typing import List

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split


class DatasetError(Exception):
    """Raised when a CSV cannot be loaded or validated."""


@dataclass
class Dataset:
    path: str
    feature_names: List[str]
    class_names: List[str]
    X_train: np.ndarray
    y_train: np.ndarray
    X_test: np.ndarray
    y_test: np.ndarray

    @property
    def n_features(self) -> int:
        return int(self.X_train.shape[1])

    @property
    def n_train(self) -> int:
        return int(self.X_train.shape[0])

    @property
    def n_test(self) -> int:
        return int(self.X_test.shape[0])


def load_dataset(
    csv_path: str,
    *,
    test_size: float = 0.2,
    random_state: int = 42,
) -> Dataset:
    """Load, validate, split, and return a Dataset."""
    if not os.path.isfile(csv_path):
        raise DatasetError(f"Dataset file not found: {csv_path}")

    try:
        df = pd.read_csv(csv_path)
    except Exception as exc:  # noqa: BLE001
        raise DatasetError(f"Could not read CSV '{csv_path}': {exc}") from exc

    if df.empty:
        raise DatasetError(f"Dataset '{csv_path}' is empty.")
    if df.shape[1] < 2:
        raise DatasetError(
            f"Dataset '{csv_path}' must have at least one feature column and one label column."
        )

    feature_names = list(df.columns[:-1])
    label_name = df.columns[-1]

    X_df = df[feature_names]
    y_series = df[label_name]

    # --- Validate features -------------------------------------------------
    bad = [c for c in feature_names if not np.issubdtype(X_df[c].dtype, np.number)]
    if bad:
        raise DatasetError(
            f"Non-numeric feature column(s) in '{csv_path}': {bad}. "
            f"All feature columns must be numeric."
        )
    if X_df.isna().any().any():
        raise DatasetError(f"Feature columns in '{csv_path}' contain missing values.")

    # --- Validate labels ---------------------------------------------------
    if y_series.isna().any():
        raise DatasetError(f"Label column '{label_name}' contains missing values.")

    y = y_series.astype(str).to_numpy()
    class_names = sorted(set(y.tolist()))
    if len(class_names) < 2:
        raise DatasetError(
            f"Dataset '{csv_path}' must have at least 2 distinct class labels, "
            f"found {len(class_names)}."
        )

    X = X_df.to_numpy(dtype=float)

    # --- Split -------------------------------------------------------------
    try:
        X_train, X_test, y_train, y_test = train_test_split(
            X,
            y,
            test_size=test_size,
            random_state=random_state,
            stratify=y,
        )
    except ValueError as exc:
        raise DatasetError(
            f"Could not split dataset '{csv_path}': {exc}"
        ) from exc

    return Dataset(
        path=csv_path,
        feature_names=feature_names,
        class_names=class_names,
        X_train=X_train,
        y_train=y_train,
        X_test=X_test,
        y_test=y_test,
    )